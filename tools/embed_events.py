#!/usr/bin/env python3
"""Build the built-in tracks' event files (events/trackN.fcfe, made with fcfedit) into the game: src/events_builtin.h.
The PC reads events/ itself (so the editor's changes show at once); the Xbox 360 and Android read only what is built in.
Run after saving events in fcfedit:  python3 tools/embed_events.py   (the tests check it is up to date)."""
import os, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def c_string(s):
    return '\n'.join('"%s\\n"' % l.replace('\\', '\\\\').replace('"', '\\"') for l in s.rstrip('\n').split('\n')) if s.strip() else '""'
def build():
    files = sorted(glob.glob(os.path.join(ROOT, 'events', '*.fcfe')))
    out = ['// events_builtin.h - generated by tools/embed_events.py from events/*.fcfe; do not edit (save in fcfedit, then re-run it).',
           '#pragma once', 'namespace director {', 'struct Builtin { const char* key; const char* body; };', 'static const Builtin BUILTIN[] = {']
    for f in files:
        out.append('{ "%s",\n%s },' % (os.path.splitext(os.path.basename(f))[0], c_string(open(f).read())))
    out += ['{ nullptr, nullptr } };', '}', '']
    return '\n'.join(out)
if __name__ == '__main__':
    open(os.path.join(ROOT, 'src', 'events_builtin.h'), 'w').write(build()); print('events_builtin.h: %d event files' % len(glob.glob(os.path.join(ROOT, 'events', '*.fcfe'))))
