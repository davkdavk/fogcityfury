# dolphin_export.py: Tarnyloo's Dolphin (CC-BY 3.0, see README.md) into the game: src/model_dolphin.h.
#   python3 models/dolphin/dolphin_export.py          (Blender as a Python module: pip install bpy)
# The game cannot bend a mesh with bones, so the spine is posed here, seven times from bent up to bent down, and the game
# steps through the poses along a leap. Every pose has the same vertices in the same order (one triangle list), so only
# positions and normals are stored per pose; colour (read from the colour map at each vertex's UV) is stored once.
# Game axes: X the same, Y up, Z forward (the nose), metres, the origin at the middle of the body; unscaled.
import bpy, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.dirname(os.path.dirname(HERE))
BENDS = [-1, -2 / 3, -1 / 3, 0, 1 / 3, 2 / 3, 1]   # the poses; per spine bone this many times PER_BONE radians
PER_BONE = 0.075                                   # (seven bones: about 30 degrees nose to tail at full bend)
MID_Y = 0.75                                       # (Blender Y of the body's middle: the nose is at about -0.6, the flukes at 2.25)

bpy.ops.wm.open_mainfile(filepath=os.path.join(HERE, 'dolphin_midpoly.blend'))
arm = bpy.data.objects['dolphin_armature']; me = bpy.data.objects['dolphin_mesh']
for m in me.modifiers:
    if m.type == 'SUBSURF': m.show_viewport = m.show_render = False
img = bpy.data.images.load(os.path.join(HERE, 'textures', 'dolphin_colour.png')); W, H = img.size; px = list(img.pixels)
def tex(u, v):   # the colour map at (u, v), nearest texel, made linear-ish (the game's vertex colours are)
    x = min(W - 1, max(0, int(u % 1 * W))); y = min(H - 1, max(0, int(v % 1 * H))); i = (y * W + x) * 4
    return tuple(max(0.0, px[i + c]) ** 1.6 for c in range(3))
FIXED = {'dolphin_upperTeeth': (0.75, 0.72, 0.66), 'dolphin_lowerTeeth': (0.75, 0.72, 0.66), 'dolphin_cornea': (0.02, 0.02, 0.025)}

def pose(b):
    for pb in arm.pose.bones: pb.rotation_mode = 'XYZ'; pb.rotation_euler = (0, 0, 0); pb.location = (0, 0, 0); pb.scale = (1, 1, 1)
    for i in range(2, 9): arm.pose.bones['body%d' % i].rotation_euler = (b * PER_BONE, 0, 0)
    bpy.context.view_layer.update()
    m = me.evaluated_get(bpy.context.evaluated_depsgraph_get()).to_mesh(); m.calc_loop_triangles(); return m

base = pose(0); uv = base.uv_layers.active.data; keys, order, cols, idx = {}, [], [], []
for t in base.loop_triangles:
    mat = base.materials[t.material_index].name if base.materials else ''
    for k in (0, 1, 2):
        vi = t.vertices[k]; u = tuple(round(c, 4) for c in uv[t.loops[k]].uv); key = (vi, u, mat)
        if key not in keys:
            keys[key] = len(order); order.append(vi); cols.append(FIXED.get(mat) or tex(*u))
        idx.append(keys[key])
poses = []
for b in BENDS:
    m = pose(b); mw = me.matrix_world; nw = mw.to_3x3()
    vs = []
    for vi in order:
        p = mw @ m.vertices[vi].co; n = (nw @ m.vertices[vi].normal).normalized()
        vs += [p.x, p.z - 0.04, -(p.y - MID_Y), n.x, n.z, -n.y]   # Blender (x, y, z) -> game (x, z, -y), centred
    poses.append(vs)
f = lambda a: ',\n'.join(','.join('%.4g' % x for x in a[i:i + 24]) for i in range(0, len(a), 24))
out = os.path.join(REPO, 'src', 'model_dolphin.h')
with open(out, 'w') as o:
    o.write('// model_dolphin.h - generated by models/dolphin/dolphin_export.py from Tarnyloo\'s Dolphin (Blend Swap #83681, CC-BY 3.0);\n')
    o.write('// do not edit. Game axes (X, Y up, Z the nose), metres, centred on the body. Seven poses of the spine (BEND).\n#pragma once\nnamespace model_dolphin {\n')
    o.write('static const int NV = %d, NI = %d, NPOSE = %d;\nstatic const float BEND[NPOSE] = { %s };\n' % (len(order), len(idx), len(BENDS), ', '.join('%.3f' % b for b in BENDS)))
    o.write('static const float COL[] = {\n%s };\n' % f([c for col in cols for c in col]))
    o.write('static const unsigned IDX[] = {\n%s };\n' % ',\n'.join(','.join(str(x) for x in idx[i:i + 24]) for i in range(0, len(idx), 24)))
    o.write('static const float POSE[NPOSE][NV * 6] = {\n%s };\n}\n' % ',\n'.join('{\n%s }' % f(p) for p in poses))
print('dolphin: %d vertices, %d triangles, %d poses -> %s' % (len(order), len(idx) // 3, len(BENDS), out))
